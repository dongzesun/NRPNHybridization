#!/usr/bin/env python3
"""Generate Schwarzschild PN tables from Fujita's exact supplementary expression.

Only arithmetic, Pi, EulerGamma, Log and Zeta are accepted. Mathematica is not
required. Rational arithmetic is evaluated with 100 decimal digits before the
final rounding to binary64. The original expression remains the source of truth.
"""
import ast
from fractions import Fraction
import hashlib
import json
import math
from pathlib import Path
import re
import sys

import mpmath as mp

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "PYPostNewtonian/PNTerms/EMR22/dEdt_inf_22PN.nb"
CODE = ROOT / "PYPostNewtonian/Code"


def expressions():
    text = SOURCE.read_text()
    match = re.fullmatch(r"\s*dEdt8\s*=\s*SeriesData\[v,\s*0,\s*\{(.*)\},\s*0,\s*45,\s*1\];\s*", text, re.S)
    if match is None:
        raise ValueError("Unexpected SeriesData bounds or syntax")
    # Every function in this source has just one argument, so all commas
    # delimit coefficients, rather than function arguments.
    parts = match[1].split(',')
    if len(parts) != 45:
        raise ValueError("Expected 45 coefficients, including the zero 0.5PN term")
    return [ast.parse(s.strip().replace('^', '**').replace('[', '(').replace(']', ')'), mode='eval').body for s in parts]


def multiply(a, b):
    result = [mp.mpf(0)] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            result[i+j] += x*y
    return result


def polynomial(node):
    """Interpret a whitelisted AST as a polynomial in log(v)."""
    if isinstance(node, ast.Constant) and type(node.value) is int:
        return [mp.mpf(node.value)]
    if isinstance(node, ast.Name):
        return [{'Pi': mp.pi, 'EulerGamma': mp.euler}[node.id]]
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, (ast.USub, ast.UAdd)):
        sign = -1 if isinstance(node.op, ast.USub) else 1
        return [sign*x for x in polynomial(node.operand)]
    if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and len(node.args) == 1:
        name, arg = node.func.id, node.args[0]
        if name == 'Log' and isinstance(arg, ast.Name) and arg.id == 'v':
            return [mp.mpf(0), mp.mpf(1)]
        value = polynomial(arg)
        if len(value) != 1 or name not in ('Log', 'Zeta'):
            raise ValueError("Unsupported function")
        return [(mp.log if name == 'Log' else mp.zeta)(value[0])]
    if isinstance(node, ast.BinOp):
        a, b = polynomial(node.left), polynomial(node.right)
        if isinstance(node.op, (ast.Add, ast.Sub)):
            sign = -1 if isinstance(node.op, ast.Sub) else 1
            n = max(len(a), len(b))
            return [(a[i] if i < len(a) else 0) + sign*(b[i] if i < len(b) else 0) for i in range(n)]
        if isinstance(node.op, ast.Mult):
            return multiply(a, b)
        if isinstance(node.op, ast.Div) and len(b) == 1:
            return [x/b[0] for x in a]
        if isinstance(node.op, ast.Pow) and len(b) == 1 and b[0] == int(b[0]) and 0 <= b[0] <= 20:
            out = [mp.mpf(1)]
            for _ in range(int(b[0])):
                out = multiply(out, a)
            return out
    raise ValueError(f"Unsupported source syntax: {ast.dump(node)[:100]}")


def tables(dps=100):
    # Long exact coefficients produce deeply nested addition ASTs.
    sys.setrecursionlimit(20000)
    with mp.workdps(dps):
        flux = [polynomial(e) for e in expressions()]
        if max(map(len, flux)) != 8:
            raise ValueError("Expected logarithms through log(v)^7")
        flux = [[mp.nstr(x, dps) for x in row] + ['0']*(8-len(row)) for row in flux]
    def a(n):
        return Fraction(math.comb(2*n, n)*3**n, 4**n)
    energy = [-2*(a(n+1)-2*a(n)) for n in range(23)]
    return flux, energy


def generate():
    flux, energy = tables()
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    data = '"""Generated by scripts/generate_emr22.py; do not edit."""\nimport numpy as np\n'
    data += f'SOURCE_SHA256 = "{digest}"\n'
    data += 'FLUX = np.array([\n' + ''.join('    '+repr([float(x) for x in row])+',\n' for row in flux) + '], dtype=float)\n'
    data += 'ENERGY = np.array('+repr([float(x) for x in energy])+', dtype=float)\n'
    (CODE / 'EMR22Coefficients.py').write_text(data)
    (SOURCE.parent / 'coefficients_decimal.json').write_text(json.dumps({'flux': flux, 'energy_rational': [str(x) for x in energy], 'source_sha256': digest}, indent=2)+'\n')

    # Reuse the expressions actually emitted by the existing symbolic source.
    # This adds no second handwritten copy of the comparable-mass/spin physics.
    runtime = (CODE / 'PNEvolution.py').read_text()
    tree = ast.parse(runtime)
    fn = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == 'TaylorT1_6p0')
    assignments = [n for n in fn.body if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name) and n.targets[0].id in ('Flux', 'dEdV', 'Absorption')]
    if len(assignments) != 3:
        raise ValueError('Could not identify the three generated balance expressions')
    support = '"""Generated balance expressions from PNEvolution.py; do not edit."""\nfrom numba import njit\n\n@njit(cache=True)\ndef balance6(Cons, Vars):\n'
    support += ''.join('    '+ast.get_source_segment(runtime,n)+'\n' for n in assignments)
    support += '    return Flux[0], dEdV[0], Absorption[0]\n'
    (CODE / 'PNBalance6.py').write_text(support)
    print('Generated 45 flux coefficients (log degree 7), 23 energy coefficients, and 6PN balance helper.')


if __name__ == '__main__':
    generate()
